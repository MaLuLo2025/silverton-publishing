      <ul>
        <li><strong>Audio ads.</strong> A synthetic voice in a radio spot or podcast ad isn&apos;t covered.</li>
        <li><strong>Translation only.</strong> Using AI solely to translate a real human performer into another language isn&apos;t covered.</li>
        <li><strong>Expressive works.</strong> Ads for films, TV programs, streaming content, documentaries and video games are excluded, if the synthetic performer is used in the ad the same way it&apos;s used in the work.</li>
      </ul>

