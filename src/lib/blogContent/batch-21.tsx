      <p>The statute doesn&apos;t define it, and no New York guidance on the point has come to our attention. The safest reading puts the disclosure in the ad itself, where a viewer will see it without clicking: on-screen text for the length of a video segment that shows the performer, or a label on a static image. A line in your website terms won&apos;t do. Language as plain as &ldquo;This ad features an AI-generated person&rdquo; is enough to start.</p>

