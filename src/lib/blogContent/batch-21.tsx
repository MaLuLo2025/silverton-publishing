      <p>On December 22, 2025, FTC staff <a href="https://www.ftc.gov/news-events/news/press-releases/2025/12/ftc-warns-10-companies-about-possible-violations-agencys-new-consumer-review-rule" target="_blank" rel="noopener noreferrer">sent warning letters to 10 companies</a> about possible violations. The FTC said the letters were based on consumer complaints and information from the companies, that they &ldquo;are not formal determinations&rdquo; of a violation, and that violations &ldquo;can result in the filing of a federal lawsuit or other legal action, and civil penalties of up to $53,088 per violation.&rdquo; That figure is the current inflation-adjusted maximum in <a href="https://www.ecfr.gov/current/title-16/chapter-I/subchapter-A/part-1/subpart-L/section-1.98" target="_blank" rel="noopener noreferrer">16 CFR 1.98</a>.</p>

